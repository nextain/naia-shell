export function bookLocation(
	locale: AppLocale,
	path: string,
	title: string,
): string {
	const part = path.startsWith("fable/")
		? bookParts[locale][0]
		: path.startsWith("astra/")
			? bookParts[locale][1]
			: "";
	return [part, title].filter(Boolean).join(" · ");
}
