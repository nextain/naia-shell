export const getFallbackCardMeta = (cardId: number) =>
	FALLBACK_TAROT_CARDS[cardId] ?? null;

export const getFallbackCardInterpretation = (cardId: number) => {
	const card = getFallbackCardMeta(cardId);
	if (!card) return "";
	return `${card.nameKr} (${card.nameEn}) 카드는 ${card.keywords.join(", ")}의 흐름을 보여줍니다. 카페루아 맥락에서는 ${card.objects.map((item) => `${item.cafelua}(${item.meaning})`).join(", ")}을 통해 질문의 방향을 읽습니다.`;
};
