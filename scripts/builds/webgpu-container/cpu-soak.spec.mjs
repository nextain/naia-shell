// #794/#824 P04: bounded, isolated CPU lifecycle soak; never target production.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
const dir = process.env.TMPDIR;
const base = process.env.NAIA_TEST_URL;
const inference = process.env.NAIA_TEST_INFERENCE;
assert(dir?.startsWith('/') && process.env.NAIA_WEB_SOURCE_DIR?.startsWith('/'));
assert(/^http:\/\/127\.0\.0\.1:\d+$/.test(base), 'Explicit loopback URL required');
const project = process.env.NAIA_TEST_PROJECT ?? 'naia-026-r6';
assert(/^naia-026-r[67]$/.test(project), 'Only round6/round7 isolated test projects are allowed');
assert.equal(inference, `${project}_inference_1`);
const container = JSON.parse(execFileSync('podman', ['inspect', inference]))[0];
assert.equal(container.Config.Labels['io.podman.compose.project'], project);
assert(!container.HostConfig.DeviceRequests?.length && !container.HostConfig.Devices?.length, 'CPU only');
const require = createRequire(`${process.env.NAIA_WEB_SOURCE_DIR}/packages/shell/package.json`);
const { chromium, expect } = require('@playwright/test');
mkdirSync(`${dir}/r6-soak-shots`, { recursive: true });
const report = { startedAt: new Date().toISOString(), cycles: [], quality: [], errors: [] };
const browser = await chromium.launch({ args: ['--no-sandbox'] });
const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
await context.route('**/*', r => new URL(r.request().url()).origin === base ? r.continue() : r.abort());
const page = await context.newPage();
page.on('pageerror', e => report.errors.push(String(e)));
const shot = name => page.screenshot({ path: `${dir}/r6-soak-shots/${name}.png` });
try {
  console.log('[cpu-soak] setup', report.startedAt);
  await page.goto(base);
  await page.waitForFunction(() => !!window.__NAIA_WEB_ADK_STATUS__ && window.__NAIA_WEB_ADK_STATUS__().phase !== 'checking', null, { timeout: 60000 });
  if (await page.evaluate(() => window.__NAIA_WEB_ADK_STATUS__().phase) === 'needs-setup') await page.getByTestId('web-workspace-start-default').click();
  await page.waitForFunction(() => window.__NAIA_WEB_ADK_STATUS__().phase === 'ready', null, { timeout: 60000 });
  const settings = page.locator('.app-bar-settings');
  await settings.click();
  await shot("settings-entry");
  await page.locator('[data-settings-tab="brain"]').click();
  await page.locator('#provider-select').selectOption('local-container');
  const panel = page.getByTestId('local-container-models');
  await expect(panel.locator('select')).toBeVisible({ timeout: 15000 });
  await panel.locator('select').selectOption('qwen2.5:0.5b');
  await expect(page.locator('#tools-toggle')).toBeDisabled();
  await expect(page.locator('#tools-toggle')).not.toBeChecked();
  await expect(page.getByTestId('local-container-limits')).toContainText(/Chat only|대화 전용/);
  await shot('limits');
  const bounds = await panel.boundingBox();
  assert(bounds.width >= 250 && bounds.x >= 0 && bounds.x + bounds.width <= 391);
  await settings.click();
  const input = page.locator('.naia-chat-area .chat-input');
  await expect(input).toBeEnabled({ timeout: 20000 });
  const requests = [];
  page.on('request', r => { if (r.url().endsWith('/local-llm/v1/chat/completions')) requests.push(r.postDataJSON()); });
  for (let cycle = 1; cycle <= 10; cycle++) {
    const started = Date.now();
    await input.fill('Write a long story about a blue ocean, at least 1000 words.'); await input.press('Enter');
    await expect(page.locator('.chat-cancel-btn')).toBeVisible({ timeout: 15000 });
    await page.waitForFunction(() => (document.querySelector('.assistant.streaming .message-content')?.textContent?.length ?? 0) > 20, null, { timeout: 120000 });
    if (cycle === 1) await shot('streaming');
    await page.locator('.chat-cancel-btn').evaluate(b => { b.click(); b.click(); });
    await expect(page.locator('.chat-cancel-btn')).toHaveCount(0, { timeout: 15000 });
    await expect(input).toBeEnabled();
    execFileSync('podman', ['stop', '--time', '1', inference]);
    await settings.click(); await panel.locator('button').click();
    await expect(panel.locator('[role="alert"]')).toBeVisible({ timeout: 20000 });
    if (cycle === 1) await shot('stopped-error');
    const recoveryStarted = Date.now();
    execFileSync('podman', ['start', inference]);
    await expect.poll(async () => (await context.request.get(`${base}/local-llm/v1/models`, { timeout: 5000 })).status(), { timeout: 30000 }).toBe(200);
    const recoveryMs = Date.now() - recoveryStarted;
    await panel.locator('button').focus(); await panel.locator('button').press('Enter');
    await expect(panel.locator('select')).toBeVisible();
    await settings.click();
    const responseEvent = page.waitForResponse(r => r.url().endsWith('/local-llm/v1/chat/completions'));
    await input.fill('Write a long story about a green forest, at least 1000 words.'); await input.press('Enter');
    assert.equal((await responseEvent).status(), 200);
    await page.waitForFunction(() => (document.querySelector('.assistant.streaming .message-content')?.textContent?.length ?? 0) > 20, null, { timeout: 120000 });
    await page.locator('.chat-cancel-btn').click();
    await expect(page.locator('.chat-cancel-btn')).toHaveCount(0, { timeout: 15000 });
    await expect(input).toBeEnabled();
    report.cycles.push({ cycle, elapsedMs: Date.now() - started, recoveryMs, recoveredWithin30s: recoveryMs <= 30000, recoveredStream: true, recoveryCancelled: true });
    console.log('[cpu-soak] cycle', cycle, report.cycles.at(-1));
  }
  await shot('recovered');
  await settings.click();
  await page.route('**/local-llm/v1/models', r => r.fulfill({ json: { data: [] } }));
  await panel.locator('button').click(); await expect(panel.locator('select')).toHaveCount(0);
  await expect(panel.locator('[role="status"]')).toBeVisible(); await shot('empty');
  await page.unroute('**/local-llm/v1/models'); await panel.locator('button').click();
  await expect(panel.locator('select')).toBeVisible();
  assert(requests.length >= 20, 'Actual Worker requests must be observed');
  assert(requests.every(r => !r.tools?.length), 'No tools sent for unsupported provider');
  assert.equal(report.errors.length, 0);
  report.passed = true;
} catch (error) {
  await shot("failure");
  writeFileSync(`${dir}/r6-soak-failure.html`, await page.content());
  throw error;
} finally {
  // Leave no stopped test inference even on assertion failure; caller owns compose down.
  execFileSync('podman', ['start', inference]);
  report.finishedAt = new Date().toISOString();
  writeFileSync(`${dir}/r6-soak-report.json`, JSON.stringify(report, null, 2));
  await browser.close();
}
